// Copies the scene engine from the design canvas into the site, so the site draws
// exactly what the canvas boards show.
//   node tools/sync-diorama.mjs path/to/project/Diorama.dc.html
// Writes assets/js/canvas-diorama.js (scenes + renderer) and assets/css/diorama.css (idle animations).
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) { console.error('usage: node tools/sync-diorama.mjs <Diorama.dc.html>'); process.exit(1); }
const html = readFileSync(src, 'utf8');
const root = new URL('..', import.meta.url);

const script = html.match(/<script type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/)?.[1];
const css = html.match(/<style>([\s\S]*?)<\/style>/)?.[1];
const head = 'class Component extends DCLogic {';
if (!script || !css || !script.includes(head)) { console.error('Diorama.dc.html: scene script or style not found'); process.exit(1); }

const js = `// Generated by tools/sync-diorama.mjs from the design canvas (project/Diorama.dc.html). Do not edit by hand.
/* eslint-disable */
${script.replace(head, 'export class CanvasDiorama {\n  constructor(props) { this.props = props || {}; }').trim()}
`;
writeFileSync(new URL('assets/js/canvas-diorama.js', root), js);
writeFileSync(new URL('assets/css/diorama.css', root), `/* Generated by tools/sync-diorama.mjs from the design canvas. */\n${css.replace(/body\{margin:0\}\s*/, '').trim()}\n`);
console.log('wrote assets/js/canvas-diorama.js and assets/css/diorama.css');
